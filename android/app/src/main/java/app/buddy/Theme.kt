package app.buddy

import androidx.compose.runtime.getValue
import androidx.compose.runtime.mutableStateOf
import androidx.compose.runtime.setValue
import androidx.compose.material3.ColorScheme
import androidx.compose.material3.darkColorScheme
import androidx.compose.material3.lightColorScheme
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.toArgb
import app.buddy.design.BuddyDark
import app.buddy.design.BuddyLight

/**
 * Buddy's look, chosen in Settings → Look: follow the phone (the default), Light or Dark.
 * The colours come from the design tokens (app.buddy.design.BuddyTokens, generated by
 * buddy-redesign/06-design-system/build_tokens.py, every text colour checked for 4.5:1 contrast).
 * Every screen takes its colours from [Pal]; changing [Theme.light] redraws the whole app at once.
 */
object Theme {
    var light by mutableStateOf(true)
    /** The owner's choice in Settings → Look: [SYSTEM], [LIGHT] or [DARK] ([DEFAULT] from earlier versions is dark). */
    var choice by mutableStateOf("system")
    const val SYSTEM = "system"
    const val LIGHT = "light"
    const val DARK = "dark"
    /** What earlier versions stored for the dark look. */
    const val DEFAULT = "default"

    /** Whether the light look shows, for a stored choice and the phone's own dark-mode setting. */
    fun isLight(choice: String, phoneDark: Boolean): Boolean = when (choice) {
        LIGHT -> true
        DARK, DEFAULT -> false
        else -> !phoneDark
    }

    /** The name server pages understand (`?theme=`). */
    val pageTheme get() = if (light) LIGHT else DARK
}

/** Material's own parts (chips, fields, buttons, menus) in the same design tokens as [Pal], for every screen. */
fun buddyColorScheme(): ColorScheme = if (Theme.light) lightColorScheme(primary = Pal.accent, background = Pal.bg,
    surface = Pal.bg, surfaceVariant = Pal.panel, onPrimary = Pal.onChip, onBackground = Pal.text, onSurface = Pal.text,
    onSurfaceVariant = Pal.dim, secondaryContainer = Pal.placeholder, onSecondaryContainer = Pal.text,
    primaryContainer = Pal.placeholder, onPrimaryContainer = Pal.link, outline = Pal.track)
else darkColorScheme(primary = Pal.accent, background = Pal.bg, surface = Pal.panel, surfaceVariant = Pal.panel,
    onPrimary = Pal.onChip, onBackground = Pal.text, onSurface = Pal.text, onSurfaceVariant = Pal.dim,
    secondaryContainer = Pal.placeholder, onSecondaryContainer = Pal.text,
    primaryContainer = Pal.placeholder, onPrimaryContainer = Pal.link, outline = Pal.track)

object Pal {
    private fun pick(dark: Color, light: Color) = if (Theme.light) light else dark

    val bg get() = pick(BuddyDark.background, BuddyLight.background)        // the screen
    val panel get() = pick(BuddyDark.surface, BuddyLight.surface)           // tiles, bubbles, cards
    val track get() = pick(BuddyDark.border, BuddyLight.border)             // bar tracks, unselected chips, lines
    val placeholder get() = pick(BuddyDark.primarySoft, BuddyLight.primarySoft) // empty image / map tiles
    val text get() = pick(BuddyDark.text, BuddyLight.text)
    val bright get() = pick(BuddyDark.text, BuddyLight.text)
    val soft get() = pick(BuddyDark.text2, BuddyLight.text2)
    val dim get() = pick(BuddyDark.text2, BuddyLight.text2)
    val accent get() = pick(BuddyDark.primary, BuddyLight.primary)
    val link get() = pick(BuddyDark.primary, BuddyLight.primary)
    val bar get() = pick(BuddyDark.primary, BuddyLight.primary)
    val warn get() = pick(BuddyDark.warning, BuddyLight.warning)
    val bad get() = pick(BuddyDark.critical, BuddyLight.critical)
    val info get() = pick(BuddyDark.critical, BuddyLight.critical)          // system notes ("ⓘ")
    val good get() = pick(BuddyDark.success, BuddyLight.success)
    val listening get() = pick(BuddyDark.listening, BuddyLight.listening)
    val talking get() = pick(BuddyDark.speaking, BuddyLight.speaking)
    val thinking get() = pick(BuddyDark.thinking, BuddyLight.thinking)
    val chip get() = pick(BuddyDark.primary, BuddyLight.primary)            // a selected chip
    val chipSoft get() = pick(BuddyDark.primary, BuddyLight.primary)        // the selected half of Talk | Listen-in
    val onChip get() = pick(BuddyDark.onPrimary, BuddyLight.onPrimary)      // text on a selected chip or a coloured button

    /** The server pages' background, before one loads (the tokens' background). */
    val pageBg get() = "#%06X".format(0xFFFFFF and bg.toArgb())
}
