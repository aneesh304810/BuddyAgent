for key, (fdc, portion, cuisines, meals, diet) in DISHES.items():
    name = food.loc[food.fdc_id == fdc, "description"].iloc[0]
    rows = fn[(fn.fdc_id == fdc) & fn.nutrient_id.isin(NUT)]
    per100 = {NUT[int(r.nutrient_id)]: round(float(r.amount), 2) for r in rows.itertuples()}
